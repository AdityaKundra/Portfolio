// Compiles src/content/posts/*.md into a typed module, so Markdown costs nothing in the
// browser and the Ask function can read posts as plain Node ESM. Runs on dev and build.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { marked } from 'marked'

const DIR = 'src/content/posts'
const OUT = 'src/content/posts.generated.ts'

const parse = (file) => {
  const raw = readFileSync(join(DIR, file), 'utf8')
  const match = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!match) throw new Error(`${file}: missing frontmatter`)
  const meta = Object.fromEntries(
    match[1].split('\n').map((line) => {
      const index = line.indexOf(':')
      return [line.slice(0, index).trim(), line.slice(index + 1).trim()]
    }),
  )
  for (const key of ['title', 'kind', 'date', 'summary']) if (!meta[key]) throw new Error(`${file}: missing ${key}`)
  if (!['blog', 'note'].includes(meta.kind)) throw new Error(`${file}: kind must be blog or note`)
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) throw new Error(`${file}: date must be YYYY-MM-DD`)
  const html = marked.parse(match[2].trim(), { async: false })
  return {
    slug: file.replace(/\.md$/, ''),
    title: meta.title,
    kind: meta.kind,
    date: meta.date,
    summary: meta.summary,
    tags: (meta.tags ?? '').replace(/[[\]]/g, '').split(',').map((tag) => tag.trim()).filter(Boolean),
    html,
    text: html.replace(/<[^>]+>/g, ' ').replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim(),
  }
}

const posts = readdirSync(DIR)
  .filter((file) => file.endsWith('.md'))
  .map(parse)
  .sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug))

writeFileSync(
  OUT,
  `// Generated by scripts/build-posts.mjs. Edit the Markdown in src/content/posts instead.
export interface Post {
  slug: string
  title: string
  kind: 'blog' | 'note'
  date: string
  summary: string
  tags: string[]
  html: string
  text: string
}

export const posts: Post[] = ${JSON.stringify(posts, null, 2)}
`,
)
console.log(`Compiled ${posts.length} posts`)
